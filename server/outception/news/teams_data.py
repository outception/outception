def _merge_lists(
    *dicts: dict[str, tuple[str, str, list[str]]],
) -> dict[str, tuple[str, str, list[str]]]:
    merged: dict[str, tuple[str, str, list[str]]] = {}
    for d in dicts:
        for key, (kicker, suffix, teams) in d.items():
            if key in merged:
                merged[key] = (merged[key][0], merged[key][1], merged[key][2] + teams)
            else:
                merged[key] = (kicker, suffix, list(teams))
    return merged


