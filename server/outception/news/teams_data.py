def _build_feeds() -> list[TeamFeed]:
    feeds: list[TeamFeed] = list(_SPORT_FEEDS)
    seen: set[str] = {sid for _q_, sid, _n, _k in _SPORT_FEEDS}
    for sport_key, (kicker, suffix, teams) in _merge_lists(
        _TEAM_LISTS,
        _TEAM_LISTS_EXTRA,
        _TEAM_LISTS_EXTRA2,
        _TEAM_LISTS_EXTRA3,
        _TEAM_LISTS_EXTRA4,
        _TEAM_LISTS_EXTRA5,
    ).items():
        for team in teams:
            source_id = f"team-{sport_key}-{_slug(team)}"
            if source_id in seen:
                continue
            seen.add(source_id)
            query = _q(f"{team} {suffix}") if suffix else _q(team)
            feeds.append((query, source_id, team, kicker))
    return feeds


